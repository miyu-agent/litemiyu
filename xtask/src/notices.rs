//! 第三方许可证清单 `THIRD-PARTY-LICENSES.txt`（照 Miyu 仓库 `xtask/src/notices.rs` 搬的）：发出去的程序
//! 里编进了的第三方包，每个的版权和许可证原文，随发行包、系统包发（MIT、BSD、Apache 都要求分发时附上）。
//!
//! 两种清单（LM-7）：
//! - 仓库里的这一份（[`PATH`]）是三个发行目标（[`licenses::PLATFORMS`]）的并集，源码仓库照它；`cargo xtask notices` 写它，
//!   `cargo xtask check` 查它是最新的。
//! - 发行包里的那一份只算那一个目标（[`render_for`]）：macOS 的包里不列只在 Linux 用的库（`linux-raw-sys`、`openssl-probe`、
//!   musl），Linux 的包里不列只在 macOS 用的（`security-framework`、`core-foundation`）。`cargo xtask dist` 现写进包里，
//!   `dist-check` 重算一遍对。
//!
//! 每个目标取正常依赖（开发依赖、构建依赖不编进程序，不算），每个包读它源码目录里带的许可证文件；一份都没带的用这里自带的
//! 标准原文，版权行写清单里的 `authors`。原文一字不差的合成一段，段前列出用它的包。编进程序的第三方数据（[`DATA`]）的原文
//! 也并进来。按名字排，同样的依赖图生成出来一字不差。
//!
//! `cargo xtask notices` 写这份文件；`cargo xtask check` 重算一遍，和仓库里的不一样就算没过，算在「许可证」那一项里。

use std::collections::{BTreeMap, BTreeSet};
use std::path::{Path, PathBuf};

use serde_json::Value;

use crate::licenses;

/// 这份清单在仓库里的位置。
pub const PATH: &str = "THIRD-PARTY-LICENSES.txt";

/// 包没带许可证文件时用的标准原文：SPDX 编号和原文，`{authors}` 换成清单里的作者。
const STANDARD: [(&str, &str); 3] = [
    ("MIT", include_str!("notices/MIT.txt")),
    ("Apache-2.0", include_str!("notices/Apache-2.0.txt")),
    ("BSD-3-Clause", include_str!("notices/BSD-3-Clause.txt")),
];

/// 编进程序的第三方数据：写在段前的说明、原文在仓库里的位置、哪些目标带它。（models.dev 的目录快照 LM-9 起不编进程序了，用到时
/// 从网上取。）tokyonight 两套配色照 Miyu 终端带的那一份写成常量（`theme/builtin.rs`），Miyu 终端的清单也列它，每个目标都带。
/// musl（LM-6）：Linux 的两份全静态的（`*-unknown-linux-musl`）把 Rust 工具链自带的 musl 的 C 库和分配器链进程序，MIT 要求附上
/// 版权；原文照本机 musl 1.2.6 的 `COPYRIGHT`（工具链 1.97 自带的是 1.2.5，照符号判的；两版这份文件有没有差没核，不联网）。
/// macOS 的那一份链的是系统的 libSystem，不带它。
pub(crate) const DATA: [Data; 2] = [
    Data {
        label: "musl libc (statically linked into the Linux builds, x86_64-unknown-linux-musl and aarch64-unknown-linux-musl: the C library and its allocator, from the Rust toolchain's self-contained musl)",
        path: "resources/licenses/musl-COPYRIGHT",
        carried: |target| target.ends_with("-musl"),
    },
    Data {
        label: "TokyoNight color palette (built into litemiyu theme/builtin.rs; ported from folke/tokyonight.nvim)",
        path: "resources/tui/themes/LICENSE-tokyonight.txt",
        carried: |_| true,
    },
];

/// 编进程序的一样第三方数据。
pub(crate) struct Data {
    /// 写在段前的说明。
    pub(crate) label: &'static str,
    /// 原文在仓库里的位置。
    pub(crate) path: &'static str,
    /// 编哪个目标时带它。
    pub(crate) carried: fn(&str) -> bool,
}

/// 文件名照大写比，以这几样开头的是许可证文件。
const NAMES: [&str; 5] = ["LICENSE", "LICENCE", "COPYING", "NOTICE", "UNLICENSE"];

/// 清单开头的两行；第三行写这份算的是哪几个目标（[`render_for`]）。
const HEAD: &str = "Third-party software included in LiteMiyu, with the full text of each license.\n\
Generated by `cargo xtask notices` from the dependency graph; do not edit by hand.\n";

/// 分段的线。
const RULE: &str =
    "================================================================================";

/// 编进程序的一个第三方包。
#[derive(Debug, Clone, PartialEq, Eq)]
pub(crate) struct Shipped {
    pub(crate) name: String,
    pub(crate) version: String,
    /// `license` 的原文，没写的是空的。
    pub(crate) license: Option<String>,
    pub(crate) authors: Vec<String>,
    /// 源码目录：`Cargo.toml` 所在的那一层。
    pub(crate) dir: PathBuf,
    /// 清单里 `license-file` 指的文件，相对源码目录。
    pub(crate) license_file: Option<String>,
}

impl Shipped {
    /// 段前列它的那一行：名字、版本，写了 `license` 的带上。
    fn label(&self) -> String {
        match &self.license {
            Some(license) => format!("{} {} ({license})", self.name, self.version),
            None => format!("{} {}", self.name, self.version),
        }
    }
}

/// 写这份清单。
///
/// # Errors
///
/// 生成不了（见 [`render`]）、写不进。
pub fn write(root: &Path, cargo: &str) -> Result<(), String> {
    let text = render(root, cargo)?;
    std::fs::write(root.join(PATH), text).map_err(|e| format!("写不了 {PATH}：{e}"))
}

/// 查：照依赖图生成的，和仓库里的那份一字不差。
pub fn check(root: &Path, cargo: &str) -> Vec<String> {
    let expected = match render(root, cargo) {
        Ok(text) => text,
        Err(e) => return vec![e],
    };
    match std::fs::read_to_string(root.join(PATH)) {
        Ok(actual) if actual == expected => Vec::new(),
        Ok(_) => vec![format!("{PATH} 不是最新的，跑 cargo xtask notices")],
        Err(_) => vec![format!("没有 {PATH}，跑 cargo xtask notices")],
    }
}

/// 仓库里的那一份：三个发行目标的并集（[`render_for`]）。
///
/// # Errors
///
/// 同 [`render_for`]。
pub fn render(root: &Path, cargo: &str) -> Result<String, String> {
    render_for(root, cargo, &licenses::PLATFORMS)
}

/// 照 `targets` 这几个目标的依赖图、各包带的许可证文件生成清单：几个目标的包合在一起，[`DATA`] 里有一个目标带的就列。
///
/// # Errors
///
/// `cargo metadata` 跑不了；有包的许可证文件读不了、是空的；有包一份都没带、`license` 里也没有自带原文的那几种；资源里
/// 第三方数据的原文读不了。
pub fn render_for(root: &Path, cargo: &str, targets: &[&str]) -> Result<String, String> {
    let mut all = BTreeMap::new();
    for platform in targets {
        let json = licenses::metadata(root, cargo, platform)
            .map_err(|e| format!("跑不了 cargo metadata（{platform}）：{e}"))?;
        for package in shipped(&json) {
            all.insert((package.name.clone(), package.version.clone()), package);
        }
    }
    let mut groups: BTreeMap<String, BTreeSet<String>> = BTreeMap::new();
    for package in all.values() {
        for text in texts(package)? {
            groups.entry(text).or_default().insert(package.label());
        }
    }
    for data in DATA {
        if !targets.iter().any(|target| (data.carried)(target)) {
            continue;
        }
        let path = data.path;
        let text = read(&root.join(path)).map_err(|e| format!("{path}：{e}"))?;
        groups
            .entry(text)
            .or_default()
            .insert(data.label.to_string());
    }
    Ok(page(targets, groups))
}

/// 从 `cargo metadata` 的输出里取：从工作区顺着正常依赖走得到的第三方包。
pub(crate) fn shipped(json: &Value) -> Vec<Shipped> {
    let ids = |value: &Value| -> Vec<String> {
        value
            .as_array()
            .into_iter()
            .flatten()
            .filter_map(|item| item.as_str().map(str::to_string))
            .collect()
    };
    let members: BTreeSet<String> = ids(&json["workspace_members"]).into_iter().collect();
    let mut normal: BTreeMap<String, Vec<String>> = BTreeMap::new();
    for node in json["resolve"]["nodes"].as_array().into_iter().flatten() {
        let Some(id) = node["id"].as_str() else {
            continue;
        };
        let deps = node["deps"]
            .as_array()
            .into_iter()
            .flatten()
            .filter(|dep| {
                dep["dep_kinds"]
                    .as_array()
                    .into_iter()
                    .flatten()
                    .any(|kind| kind["kind"].is_null())
            })
            .filter_map(|dep| dep["pkg"].as_str().map(str::to_string))
            .collect();
        normal.insert(id.to_string(), deps);
    }
    let mut reached = BTreeSet::new();
    let mut next: Vec<String> = members.iter().cloned().collect();
    while let Some(id) = next.pop() {
        if reached.insert(id.clone()) {
            next.extend(normal.get(&id).into_iter().flatten().cloned());
        }
    }
    json["packages"]
        .as_array()
        .into_iter()
        .flatten()
        .filter(|package| {
            package["id"]
                .as_str()
                .is_some_and(|id| reached.contains(id) && !members.contains(id))
        })
        .map(|package| Shipped {
            name: package["name"].as_str().unwrap_or_default().to_string(),
            version: package["version"].as_str().unwrap_or_default().to_string(),
            license: package["license"].as_str().map(str::to_string),
            authors: ids(&package["authors"]),
            dir: package["manifest_path"]
                .as_str()
                .map(Path::new)
                .and_then(Path::parent)
                .map(Path::to_path_buf)
                .unwrap_or_default(),
            license_file: package["license_file"].as_str().map(str::to_string),
        })
        .collect()
}

/// 一个包的许可证原文：带了文件的照文件，一份都没带的照 [`STANDARD`]。
pub(crate) fn texts(package: &Shipped) -> Result<Vec<String>, String> {
    let head = format!("{} {}", package.name, package.version);
    let mut files = BTreeSet::new();
    let entries = std::fs::read_dir(&package.dir)
        .map_err(|e| format!("{head}：读不了源码目录 {}：{e}", package.dir.display()))?;
    for entry in entries {
        let entry =
            entry.map_err(|e| format!("{head}：读不了源码目录 {}：{e}", package.dir.display()))?;
        let upper = entry.file_name().to_string_lossy().to_uppercase();
        if !NAMES.iter().any(|name| upper.starts_with(name)) {
            continue;
        }
        let path = entry.path();
        match path.is_dir() {
            true => {
                let inside = std::fs::read_dir(&path)
                    .map_err(|e| format!("{head}：读不了 {}：{e}", path.display()))?;
                for each in inside {
                    let each =
                        each.map_err(|e| format!("{head}：读不了 {}：{e}", path.display()))?;
                    files.insert(each.path());
                }
            }
            false => {
                files.insert(path);
            }
        }
    }
    if let Some(file) = &package.license_file {
        files.insert(package.dir.join(file));
    }
    if files.is_empty() {
        return standard(package).ok_or_else(|| {
            let license = package.license.as_deref().unwrap_or("没写");
            format!("{head}：没带许可证文件，{license} 也没有自带的原文，要人看过")
        });
    }
    files
        .iter()
        .map(|path| read(path).map_err(|e| format!("{head}：{}：{e}", path.display())))
        .collect()
}

/// 没带许可证文件的包：`license` 里出现的、[`STANDARD`] 有原文的那几种，版权行写作者。一种都没有的是空的。
fn standard(package: &Shipped) -> Option<Vec<String>> {
    let license = package.license.as_deref()?;
    let named: BTreeSet<&str> = license
        .split(|c: char| !(c.is_ascii_alphanumeric() || c == '-' || c == '.'))
        .collect();
    let authors = match package.authors.is_empty() {
        true => format!("the {} authors", package.name),
        false => package.authors.join(", "),
    };
    let found: Vec<String> = STANDARD
        .iter()
        .filter(|(id, _)| named.contains(id))
        .map(|(_, text)| text.replace("{authors}", &authors).trim_end().to_string())
        .collect();
    (!found.is_empty()).then_some(found)
}

/// 读一份原文：换行统一成 `\n`，去掉末尾的空白；不是 UTF-8 的字节照替换字符读。空的算错。
pub(crate) fn read(path: &Path) -> Result<String, String> {
    let bytes = std::fs::read(path).map_err(|e| e.to_string())?;
    let text = String::from_utf8_lossy(&bytes)
        .replace("\r\n", "\n")
        .trim_end()
        .to_string();
    match text.trim().is_empty() {
        true => Err("是空的".to_string()),
        false => Ok(text),
    }
}

/// 拼成整份：开头写算的是哪几个目标，每段先列用它的，再是原文；段照第一个用它的排。
pub(crate) fn page(targets: &[&str], groups: BTreeMap<String, BTreeSet<String>>) -> String {
    let mut ordered: Vec<(BTreeSet<String>, String)> = groups
        .into_iter()
        .map(|(text, users)| (users, text))
        .collect();
    ordered.sort();
    let mut out = String::from(HEAD);
    out.push_str(&format!("Builds covered: {}.\n", targets.join(", ")));
    for (users, text) in ordered {
        out.push('\n');
        out.push_str(RULE);
        out.push('\n');
        for user in &users {
            out.push_str(user);
            out.push('\n');
        }
        out.push('\n');
        out.push_str(&text);
        out.push('\n');
    }
    out
}

